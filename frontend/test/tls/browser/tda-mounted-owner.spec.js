import {fileURLToPath} from 'node:url';
import {readFile} from 'node:fs/promises';
import {test,expect} from './fixtures.js';
const fixture=fileURLToPath(new URL('../../tda/fixtures/ga-regressions/carrier-classic.txt',import.meta.url));
test('TDA virtual owner survives details, graph and the downloaded blocking report',async({page,appUrl})=>{
    await page.goto(`${appUrl}/jvmscope/tda.html`);
    await page.locator('#fileInput').setInputFiles(fixture);
    const row=page.locator('#threadTableBody tr').filter({hasText:'Virtual thread #26'});
    await row.getByRole('button',{name:'Details',exact:true}).click();
    await expect(page.locator('#threadModalSummary')).toContainText('Virtual');
    await page.getByRole('tab',{name:'Locks',exact:true}).click();
    await expect(page.locator('#threadModal')).toContainText('0x00000000ffc0ebc8');
    await page.locator('#threadModalClose2').click();
    await page.locator('#dependencyGraphDetails > summary').click();
    const select=page.locator('#blockingPatternSelect');
    await expect(select).not.toContainText('Dependencies on ForkJoinPool-1-worker-1');
    await select.selectOption({label:'Dependencies on Virtual thread #26 · peak 1 · recurrence 0'});
    await expect(page.locator('#blockingPatternView')).toContainText('Blocker Virtual thread #26');
    await page.locator('#addBlockingReport').click();
    await page.getByRole('button',{name:'Preview report',exact:true}).click();
    await expect(page.frameLocator('#reportPreview iframe').locator('body')).toContainText('Dependencies on Virtual thread #26');
    await page.locator('#reportPreview input[type=checkbox]').check();
    const pending=page.waitForEvent('download');
    await page.getByRole('button',{name:'Export Markdown',exact:true}).click();
    const download=await pending;
    const markdown=await readFile(await download.path(),'utf8');
    expect(markdown).toContain('Dependencies on Virtual thread');
    expect(markdown).not.toContain('Dependencies on ForkJoinPool-1-worker-1');
});
